/**
 * Embedding SDK (PRD FR-10): programmatic access to a GRHM project on disk.
 * The CLI, the compiler server, and the LSP are all thin layers over this.
 */

export interface ProjectConfig {
  entry: string;
  outDir: string;
  root: string;
}

const SAFE_CONFIG_PATH = /^[A-Za-z0-9._/-]+$/;

function containedProjectPath(root: string, relPath: string, label: string): string {
  if (relPath.includes('\0')) throw new Error(`${label} contains a NUL byte`);
  const lexicalRoot = path.resolve(root);
  const target = path.resolve(lexicalRoot, relPath);
  const rel = path.relative(lexicalRoot, target);
  if (rel === '..' || rel.startsWith('..' + path.sep) || path.isAbsolute(rel)) {
    throw new Error(`${label} must stay inside the project root: "${relPath}"`);
  }
  if (!fs.existsSync(lexicalRoot)) return target;
  const realRoot = fs.realpathSync(lexicalRoot);
  let probe = target;
  let targetStat: fs.Stats | undefined;
  try {
    targetStat = fs.lstatSync(target);
  } catch {
    targetStat = undefined;
  }
  if (targetStat?.isSymbolicLink() === true) {
    try {
      probe = fs.realpathSync(target);
    } catch {
      throw new Error(`${label} is a dangling symbolic link: "${relPath}"`);
    }
  } else if (targetStat === undefined) {
    probe = path.dirname(target);
    while (!fs.existsSync(probe) && path.dirname(probe) !== probe) probe = path.dirname(probe);
  }
  const realProbe = fs.existsSync(probe) ? fs.realpathSync(probe) : probe;
  const realRel = path.relative(realRoot, realProbe);
  if (realRel === '..' || realRel.startsWith('..' + path.sep) || path.isAbsolute(realRel)) {
    throw new Error(`${label} resolves outside the project root: "${relPath}"`);
  }
  return target;
}

function normalizeConfigPath(root: string, value: string, label: 'entry' | 'outDir'): string {
  if (value === '' || !SAFE_CONFIG_PATH.test(value) || value.includes('\\')) {
    throw new Error(`${label} must be a non-empty relative path using letters, digits, '.', '_', '-', and '/'`);
  }
  if (path.isAbsolute(value)) throw new Error(`${label} must be relative to the project root`);
  const target = containedProjectPath(root, value, label);
  const rel = path.relative(path.resolve(root), target).split(path.sep).join('/');
  if (label === 'entry' && rel === '') throw new Error('entry must name a file');
  return rel === '' ? '.' : rel;
}

function validatedConfig(config: ProjectConfig): ProjectConfig {
  const root = path.resolve(config.root);
  return {
    root,
    entry: normalizeConfigPath(root, config.entry, 'entry'),
    outDir: normalizeConfigPath(root, config.outDir, 'outDir'),
  };
}

export function loadConfig(cwd: string): ProjectConfig {
  let dir = cwd;
  for (;;) {
    const candidate = path.join(dir, 'grhm.json');
    if (fs.existsSync(candidate)) {
      const raw = JSON.parse(fs.readFileSync(candidate, 'utf8')) as { entry?: string; outDir?: string };
      return validatedConfig({ entry: raw.entry ?? 'app.grhm', outDir: raw.outDir ?? 'src/gen', root: dir });
    }
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return validatedConfig({ entry: 'app.grhm', outDir: 'src/gen', root: cwd });
}

export interface CheckSummary {
  ok: boolean;
  revision: string;
  diagnostics: Diagnostic[];
}

const ARTIFACT_MANIFEST = '.grhm-artifacts.json';
const GENERATED_MARKER = '/* Generated by grhm.';
const LEGACY_OPTIONAL_ARTIFACTS = ['components.tsx', 'i18n.ts', 'lib.ts', 'server.ts', 'state.ts'];

function safeArtifactPath(outDir: string, name: string): string {
  const target = containedProjectPath(outDir, name, 'generated artifact');
  if (path.resolve(outDir) === target) throw new Error(`unsafe generated artifact path: "${name}"`);
  return target;
}

function isGeneratedFile(file: string): boolean {
  if (!fs.existsSync(file) || !fs.statSync(file).isFile()) return false;
  return fs.readFileSync(file, 'utf8').startsWith(GENERATED_MARKER);
}

function legacyArtifacts(outDir: string): Set<string> {
  const out = new Set<string>();
  for (const name of LEGACY_OPTIONAL_ARTIFACTS) {
    if (isGeneratedFile(path.join(outDir, name))) out.add(name);
  }
  const pagesDir = path.join(outDir, 'pages');
  if (fs.existsSync(pagesDir) && fs.statSync(pagesDir).isDirectory()) {
    for (const entry of fs.readdirSync(pagesDir, { withFileTypes: true })) {
      if (!entry.isFile() || !entry.name.endsWith('.tsx')) continue;
      const name = `pages/${entry.name}`;
      if (isGeneratedFile(path.join(outDir, name))) out.add(name);
    }
  }
  return out;
}

function previousArtifacts(outDir: string): Set<string> {
  const manifest = path.join(outDir, ARTIFACT_MANIFEST);
  if (!fs.existsSync(manifest)) return legacyArtifacts(outDir);
  try {
    const parsed = JSON.parse(fs.readFileSync(manifest, 'utf8')) as { schema?: unknown; files?: unknown };
    if (parsed.schema !== 1 || !Array.isArray(parsed.files) || !parsed.files.every((name) => typeof name === 'string')) {
      return legacyArtifacts(outDir);
    }
    return new Set(parsed.files);
  } catch {
    return legacyArtifacts(outDir);
  }
}

export class GrhmProject {
  readonly config: ProjectConfig;
  /** Unsaved buffer contents (used by the LSP), keyed by root-relative path. */
  readonly overlay = new Map<string, string>();

  constructor(config: ProjectConfig) {
    this.config = validatedConfig(config);
  }

  static fromCwd(cwd: string): GrhmProject {
    return new GrhmProject(loadConfig(cwd));
  }

  private reader(): ReadFile {
    return (relPath: string) => {
      let abs: string;
      try {
        abs = containedProjectPath(this.config.root, relPath, 'project file');
      } catch {
        return undefined;
      }
      const overlaid = this.overlay.get(relPath);
      if (overlaid !== undefined) return overlaid;
      return fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : undefined;
    };
  }

  load(): Project {
    return loadProject(this.config.entry, this.reader());
  }

  /** Existence checks for interop modules (relative files and npm packages). */
  private interopDiagnostics(app: AppModel): Diagnostic[] {
    const out: Diagnostic[] = [];
    const seen = new Set<string>();
    if (app.auth?.provider !== undefined && !fs.existsSync(containedProjectPath(this.config.root, app.auth.provider, 'identity provider'))) {
      out.push(makeDiag('E602', 'error', 'Identity provider module not found: ' + app.auth.provider, { span: app.auth.node.span, nodeId: app.auth.node.id, received: app.auth.provider }));
    }
    for (const [, imp] of app.imports) {
      if (seen.has(imp.module)) continue;
      seen.add(imp.module);
      if (imp.module.startsWith('./') || imp.module.startsWith('../')) {
        if (!fs.existsSync(path.join(this.config.root, imp.module))) {
          out.push(
            makeDiag('E602', 'error', `Interop module not found: "${imp.module}" (relative to project root)`, {
              span: imp.node.span,
              nodeId: imp.node.id,
              received: imp.module,
            }),
          );
        }
      } else {
        const pkg = imp.module.startsWith('@') ? imp.module.split('/').slice(0, 2).join('/') : imp.module.split('/')[0] ?? imp.module;
        if (!fs.existsSync(path.join(this.config.root, 'node_modules', pkg))) {
          out.push(
            makeDiag('W602', 'warning', `Package "${pkg}" is not installed in node_modules; run npm install ${pkg}`, {
              span: imp.node.span,
              nodeId: imp.node.id,
              received: pkg,
            }),
          );
        }
      }
    }
    return out;
  }

  compile(): CompileResult {
    const outDirDepth = this.config.outDir.split('/').filter((s) => s !== '' && s !== '.').length;
    const result = compileProject(this.load(), { outDirDepth });
    if (result.app !== undefined) {
      result.diagnostics.push(...this.interopDiagnostics(result.app));
      if (hasErrors(result.diagnostics)) result.files.clear();
    }
    return result;
  }

  check(): CheckSummary {
    const result = this.compile();
    return { ok: !hasErrors(result.diagnostics), revision: result.revision, diagnostics: result.diagnostics };
  }

  revision(): string {
    return projectRevision(this.load());
  }

  /** Write generated artifacts; returns root-relative paths written. */
  writeArtifacts(files: Map<string, string>): string[] {
    const outDir = containedProjectPath(this.config.root, this.config.outDir, 'outDir');
    fs.mkdirSync(outDir, { recursive: true });
    const previous = previousArtifacts(outDir);
    const current = new Set(files.keys());
    const written: string[] = [];
    for (const [name, content] of files) {
      const target = safeArtifactPath(outDir, name);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
      written.push(path.relative(this.config.root, target));
    }
    for (const name of previous) {
      if (current.has(name)) continue;
      let target: string;
      try {
        target = safeArtifactPath(outDir, name);
      } catch {
        // A corrupt/tampered manifest is untrusted input. Ignore entries that
        // do not resolve inside the configured output directory.
        continue;
      }
      if (isGeneratedFile(target)) fs.unlinkSync(target);
    }
    const pagesDir = safeArtifactPath(outDir, 'pages');
    if (fs.existsSync(pagesDir) && fs.statSync(pagesDir).isDirectory() && fs.readdirSync(pagesDir).length === 0) {
      fs.rmdirSync(pagesDir);
    }
    fs.writeFileSync(
      safeArtifactPath(outDir, ARTIFACT_MANIFEST),
      JSON.stringify({ schema: 1, files: [...current].sort() }, null, 2) + '\n',
    );
    return written;
  }

  inspect(nodeId: string): { node: unknown; text: string; parentId?: string; parentOp?: string; file?: string } | undefined {
    const project = this.load();
    const allRoots = project.files.flatMap((f) => f.nodes);
    const found = findNode(allRoots, nodeId);
    if (found === undefined) return undefined;
    return {
      node: found.node,
      text: format([found.node]),
      parentId: found.parent?.id,
      parentOp: found.parent !== undefined ? opName(found.parent) : undefined,
      file: found.node.span.file,
    };
  }

  /** Apply a patch; when write is true (default) changed files are saved. */
  applyPatch(patchSource: string, write = true): PatchResult {
    if (write) return withWriteLock(this.config.root, () => this.applyPatchUnlocked(patchSource, true));
    return this.applyPatchUnlocked(patchSource, false);
  }

  private applyPatchUnlocked(patchSource: string, write: boolean): PatchResult {
    const snapshot = (write ? this.load().files : []).map((file) => ({ file: file.file, disk: fs.readFileSync(containedProjectPath(this.config.root, file.file, 'patch target'), 'utf8') }));
    const result = applyPatchToProject(this.config.entry, this.reader(), patchSource);
    if (result.ok && result.newSources !== undefined) {
      // applyPatchToProject validates the language itself, but filesystem/npm
      // interop checks live at the SDK layer. Validate the overlaid result with
      // the same project pipeline before any file is written.
      const preview = new GrhmProject(this.config);
      for (const [file, source] of this.overlay) preview.overlay.set(file, source);
      for (const [file, source] of result.newSources) preview.overlay.set(file, source);
      const checked = preview.compile();
      const interop = checked.diagnostics.filter((d) => d.code === 'E602' || d.code === 'W602');
      if (hasErrors(interop)) {
        return {
          ok: false,
          conflict: false,
          changed: [],
          diagnostics: [
            makeDiag('E503', 'error', 'Patch rejected: it would produce an invalid program'),
            ...interop,
          ],
        };
      }
      const existing = new Set(result.diagnostics.map((d) => `${d.code}:${d.span?.file ?? ''}:${d.span?.start ?? -1}`));
      result.diagnostics.push(...interop.filter((d) => !existing.has(`${d.code}:${d.span?.file ?? ''}:${d.span?.start ?? -1}`)));
    }
    if (result.ok && write && result.newSources !== undefined) {
      if (snapshot.some(({ file, disk }) => fs.readFileSync(containedProjectPath(this.config.root, file, 'patch target'), 'utf8') !== disk)) {
        return { ok: false, conflict: true, changed: [], diagnostics: [makeDiag('E504', 'error', 'Project changed during patch validation; retry against its current revision')] };
      }
      writeFiles(this.config.root, result.newSources);
    }
    return result;
  }

  /**
   * Format every project file. Returns the files that changed (or, with
   * checkOnly, the files that would change).
   */
  formatAll(style: NameStyle = 'preserve', checkOnly = false): { changed: string[]; diagnostics: Diagnostic[] } {
    if (!checkOnly) return withWriteLock(this.config.root, () => this.formatAllUnlocked(style, false));
    return this.formatAllUnlocked(style, true);
  }

  private formatAllUnlocked(style: NameStyle, checkOnly: boolean): { changed: string[]; diagnostics: Diagnostic[] } {
    const project = this.load();
    if (hasErrors(project.diagnostics)) return { changed: [], diagnostics: project.diagnostics };
    const changes = new Map<string, string>();
    const changed: string[] = [];
    for (const file of project.files) {
      const formatted = format(file.nodes, style);
      if (formatted !== file.source) {
        changed.push(file.file);
        changes.set(file.file, formatted);
      }
    }
    if (!checkOnly && changes.size > 0) writeFiles(this.config.root, changes);
    return { changed, diagnostics: project.diagnostics };
  }

  /** Playwright (browser) and Vitest (jsdom) specs for (tests ...) suites. */
  testSpec(): { spec: string | undefined; unitSpec: string | undefined; diagnostics: Diagnostic[] } {
    const result = this.compile();
    if (hasErrors(result.diagnostics) || result.app === undefined) {
      return { spec: undefined, unitSpec: undefined, diagnostics: result.diagnostics };
    }
    return { spec: genPlaywrightSpec(result.app), unitSpec: genVitestSpec(result.app, this.config.outDir), diagnostics: result.diagnostics };
  }

  /** Total semantic (list) nodes across the project. */
  countNodes(): number {
    const project = this.load();
    let count = 0;
    walkLists(project.files.flatMap((f) => f.nodes), () => {
      count += 1;
    });
    return count;
  }
}
