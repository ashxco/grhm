interface SourceMapEntry {
  source: { file: string; line: number; col: number };
  generated: { file: string; line: number }[];
}

/**
 * Source correlation map (PRD FR-7): for every semantic node, the .grhm
 * source location and every generated line that carries its data-g marker.
 */
function genSourceMap(app: AppModel, files: Map<string, string>, entryFile: string): string {
  const nodes: Record<string, SourceMapEntry> = {};
  walkLists([app.node, ...app.tests.map((t) => t.node)], (n) => {
    if (n.id === undefined) return;
    nodes[n.id] = {
      source: { file: n.span.file ?? entryFile, line: n.span.line, col: n.span.col },
      generated: [],
    };
  });
  for (const [file, content] of files) {
    if (!file.endsWith('.tsx') && !file.endsWith('.ts')) continue;
    const lines = content.split('\n');
    lines.forEach((line, i) => {
      // data-g values are emitted as JSON string expressions so an explicit
      // semantic :id can never break out of JSX attribute syntax.
      for (const match of line.matchAll(/(?:data-g=\{|grhm-node )("(?:\\.|[^"\\])*")/g)) {
        const literal = match[1];
        if (literal === undefined) continue;
        const id = JSON.parse(literal) as string;
        if (nodes[id] !== undefined) {
          nodes[id].generated.push({ file, line: i + 1 });
        }
      }
    });
  }
  return JSON.stringify({ schema: 1, entry: entryFile, nodes }, null, 2) + '\n';
}

/** Generate all output files for an analyzed, error-free program. */
export function generate(app: AppModel, options: CompileOptions = {}): Map<string, string> {
  const outDirDepth = options.outDirDepth ?? 2;
  const entryFile = options.entryFile ?? 'app.grhm';
  const { css, classFor } = genCss(app);
  const files = new Map<string, string>();
  const liveRoutes = app.apis.filter((route) => route.method === 'get').sort((a, b) => routeSpecificity(b.route) - routeSpecificity(a.route)).map((route) => ({ pattern: route.route, id: route.node.id }));
  files.set('runtime.ts', RUNTIME_SOURCE.replace('/* GRHM_LIVE_ROUTES */ []', JSON.stringify(liveRoutes)));
  files.set('helpers.ts', HELPERS_SOURCE);
  files.set('http-files.ts', runtimeSource('http-files'));
  files.set('static-server.ts', runtimeSource('static-server'));
  files.set('styles.css', css);
  if (app.locales.size > 0) files.set('i18n.ts', genI18nFile(app));
  if (app.functions.size > 0) files.set('lib.ts', genLibFile(app, outDirDepth));
  if (app.tables.size > 0 || app.apis.length > 0 || app.uploads !== undefined) {
    files.set('server.ts', genServerFile(app, outDirDepth));
    files.set('storage.ts', runtimeSource('storage'));
    files.set('db-admin.ts', runtimeSource('db-admin'));
    files.set('controls.ts', runtimeSource('controls'));
    files.set('contracts.ts', runtimeSource('contracts'));
    files.set('uploads.ts', runtimeSource('uploads'));
  }
  if (app.states.size > 0) files.set('state.ts', genStateFile(app, outDirDepth));
  const componentsFile = genComponentsFile(app, classFor, outDirDepth);
  if (componentsFile !== undefined) files.set('components.tsx', componentsFile);
  for (const page of app.pages) {
    files.set(`pages/${pageFileName(page)}.tsx`, genPageFile(page, app, classFor, outDirDepth));
  }
  files.set('App.tsx', genAppFile(app));
  files.set('sourcemap.json', genSourceMap(app, files, entryFile));
  return files;
}

/** Analyze and check pre-parsed roots, generating output when error-free. */
export function compileNodes(nodes: SExpr[], diagnostics: Diagnostic[], revision: string, options: CompileOptions = {}): CompileResult {
  if (hasErrors(diagnostics)) {
    return { files: new Map(), diagnostics, revision, app: undefined, nodes };
  }
  const app = analyze(nodes, diagnostics);
  if (app !== undefined) check(app, diagnostics);
  if (app === undefined || hasErrors(diagnostics)) {
    return { files: new Map(), diagnostics, revision, app, nodes };
  }
  return { files: generate(app, options), diagnostics, revision, app, nodes };
}

/** Full pipeline: parse, analyze, check, and (if clean) generate output files. */
export function compile(source: string, options: CompileOptions = {}): CompileResult {
  const diagnostics: Diagnostic[] = [];
  const { nodes, diagnostics: parseDiags } = parse(source);
  diagnostics.push(...parseDiags);
  const revision = computeRevision(format(nodes));
  return compileNodes(nodes, diagnostics, revision, options);
}
