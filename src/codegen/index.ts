const HEADER = '/* Generated by grhm. Do not edit by hand. */\n';

export interface CompileOptions {
  /**
   * Directory depth of the generated output below the project root (default 2
   * for src/gen). Used to rewrite project-relative interop imports.
   */
  outDirDepth?: number;
  /** Name of the entry source file, used in the source correlation map. */
  entryFile?: string;
}

/** Revision of a program: hash of its canonical formatted source. */
export function computeRevision(canonicalSource: string): string {
  return fnv1aHex(canonicalSource);
}

/** All identifier heads and operation names referenced in the given expressions. */
function collectHeads(exprs: SExpr[]): Set<string> {
  const heads = new Set<string>();
  const go = (e: SExpr): void => {
    if (e.kind === 'ident') {
      const head = e.name.split('.')[0];
      if (head !== undefined) heads.add(head);
    } else if (e.kind === 'list') {
      const first = e.items[0];
      if (first !== undefined && first.kind === 'ident') heads.add(first.name);
      for (const item of e.items) go(item);
    }
  };
  for (const e of exprs) go(e);
  return heads;
}


function inferTsType(init: SExpr, scope: Scope, app: AppModel): string {
  return init.kind === 'null' ? 'any' : typeScriptType(inferInfo(init, scope, app.tables), app.tables);
}

function storeName(state: string): string {
  return camelCase(state) + 'Store';
}

function genStateFile(app: AppModel, outDirDepth: number): string {
  const bindings = new Map<string, Binding>();
  for (const name of app.functions.keys()) {
    bindings.set(name, { kind: 'fn', js: camelCase(name) });
  }
  for (const name of app.enums.keys()) {
    bindings.set(name, { kind: 'enum', js: '' });
  }
  const uses = newUses();
  const heads = collectHeads([...app.states.values()].map((state) => state.init));
  for (const [name, imp] of app.imports) {
    if (!heads.has(name)) continue;
    const local = camelCase(name);
    bindings.set(name, { kind: 'js', js: local });
    addJsImport(uses, imp.module, imp.jsName, local, imp.isDefault);
  }
  const ctx: ExprCtx = { bindings, classFor: new Map(), uses, sameFileComponents: new Set(), defaultLocale: app.defaultLocale };
  const typeScope = stateInitializerScope(app);
  const decls: string[] = [];
  for (const [name, state] of app.states) {
    decls.push(`export const ${storeName(name)} = createStore<${inferTsType(state.init, typeScope, app)}>(${genExpr(state.init, ctx)});`);
    typeScope.set(name, initializerInfo('state', state.init, typeScope, app));
    bindings.set(name, { kind: 'state', js: `${storeName(name)}.get()` });
  }
  let out = HEADER;
  out += `import { ${['createStore', ...[...uses.helpers].sort()].join(', ')} } from './runtime';\n`;
  if (uses.i18n) out += `import { tMsg } from './i18n';\n`;
  out += jsImportLines(uses, 0, outDirDepth);
  out += libImportLines(uses, './');
  return out + '\n' + decls.join('\n') + '\n';
}

/** Import of user-defined GRHM fns from the generated lib module. */
function libImportLines(uses: FileUses, prefix: string): string {
  if (uses.libFns.size === 0) return '';
  const names = [...uses.libFns].sort().map((n) => camelCase(n));
  return `import { ${names.join(', ')} } from '${prefix}lib';\n`;
}

/** TypeScript parameter type for a declared fn parameter type. */
function fnParamTsType(typeName: string | undefined, app: AppModel): string {
  return typeScriptType(declaredType(typeName, app.tables), app.tables);
}

/** The user-defined function library: pure TypeScript, one export per (fn ...). */
function genLibFile(app: AppModel, outDirDepth: number): string {
  const uses = newUses();
  const bindings = new Map<string, Binding>();
  for (const name of app.functions.keys()) {
    bindings.set(name, { kind: 'fn', js: camelCase(name) });
  }
  for (const name of app.enums.keys()) {
    bindings.set(name, { kind: 'enum', js: '' });
  }
  const heads = collectHeads([...app.functions.values()].map((f) => f.body));
  for (const [name, imp] of app.imports) {
    if (!heads.has(name)) continue;
    const local = camelCase(name);
    bindings.set(name, { kind: 'js', js: local });
    addJsImport(uses, imp.module, imp.jsName, local, imp.isDefault);
  }
  const chunks: string[] = [];
  const typeScope = stateInitializerScope(app);
  for (const [, decl] of app.functions) {
    const inner = new Map(bindings);
    const paramNames = decl.params.map((p) => {
      const js = genBindingName(p, inner);
      inner.set(p, { kind: 'eachvar', js });
      return js;
    });
    const ctx: ExprCtx = { bindings: inner, classFor: new Map(), uses, sameFileComponents: new Set(), defaultLocale: app.defaultLocale };
    const params = paramNames.map((p, i) => `${p}: ${fnParamTsType(decl.paramTypes[i], app)}`).join(', ');
    const binding = typeScope.get(decl.name);
    const result = binding === undefined ? { type: 'unknown' as const } : inferCall(bindingInfo(binding), decl.paramTypes.map((type) => declaredType(type, app.tables)), app.tables);
    chunks.push(`${sourceMarker(decl.node.id)}\nexport function ${camelCase(decl.name)}(${params}): ${typeScriptType(result, app.tables)} {\n  return ${genExpr(decl.body, ctx)};\n}`);
  }
  let out = HEADER;
  // Helpers, not runtime: lib.ts is shared with the server and must not pull React.
  if (uses.helpers.size > 0) out += `import { ${[...uses.helpers].sort().join(', ')} } from './helpers.ts';\n`;
  if (uses.i18n) out += `import { tMsg } from './i18n.ts';\n`;
  out += jsImportLines(uses, 0, outDirDepth, true);
  return out + '\n' + chunks.join('\n\n') + '\n';
}

/** The i18n module: message catalogs + a React-free template formatter. */
function genI18nFile(app: AppModel): string {
  let out = HEADER;
  const locales: string[] = [];
  for (const [name, messages] of app.locales) {
    const entries = [...messages].map(([key, text]) => `    ${JSON.stringify(key)}: ${JSON.stringify(text)},`);
    locales.push(`  ${JSON.stringify(name)}: {\n${entries.join('\n')}\n  },`);
  }
  out += 'export const MESSAGES: Record<string, Record<string, string>> = {\n' + locales.join('\n') + '\n};\n\n';
  out += `export const DEFAULT_LOCALE = ${JSON.stringify(app.defaultLocale ?? 'en')};\n\n`;
  out += 'export function tMsg(locale: string, key: string, params?: Record<string, unknown>): string {\n';
  out += '  const catalog = MESSAGES[locale] ?? MESSAGES[DEFAULT_LOCALE] ?? {};\n';
  out += '  const fallback = MESSAGES[DEFAULT_LOCALE] ?? {};\n';
  out += '  let text = catalog[key] ?? fallback[key] ?? key;\n';
  out += '  for (const [name, value] of Object.entries(params ?? {})) {\n';
  out += "    text = text.split('{' + name + '}').join(String(value));\n";
  out += '  }\n';
  out += '  return text;\n';
  out += '}\n';
  return out;
}

function propTsType(type: PropTypeName): string {
  switch (type) {
    case 'string':
      return 'string';
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'action':
      return '() => void';
    case 'list':
      return 'any[]';
    case 'record':
    case 'any':
      return 'any';
    default: {
      const exhaustive: never = type;
      throw new Error(`unhandled prop type: ${String(exhaustive)}`);
    }
  }
}

interface FnSpec {
  fnName: string;
  propsParam: string;
  body: SExpr[];
  locals: StateDecl[];
  bindings: Map<string, Binding>;
  /** Type bindings visible before sequential local declarations. */
  typeScope: Scope;
  /** Page title expression; emits a document.title effect. */
  title?: SExpr;
}

function emitFunction(spec: FnSpec, app: AppModel, classFor: Map<string, string>, uses: FileUses, sameFile: Set<string>): string {
  const heads = collectHeads([...spec.body, ...spec.locals.map((l) => l.init), ...(spec.title !== undefined ? [spec.title] : [])]);
  // A resource hook's default is emitted in this module too. Pull in globals
  // referenced only by that default (and repeat for any newly discovered
  // resource head) so clean source cannot produce an unbound identifier.
  const expandedResources = new Set<string>();
  for (;;) {
    let changed = false;
    for (const [name, resource] of app.resources) {
      if (!heads.has(name) || expandedResources.has(name) || resource.defaultValue === undefined) continue;
      expandedResources.add(name);
      for (const dependency of collectHeads([resource.defaultValue])) {
        if (!heads.has(dependency)) {
          heads.add(dependency);
          changed = true;
        }
      }
    }
    if (!changed) break;
  }
  // (t ...) reads the current locale from the `locale` state when declared.
  if (heads.has('t') && app.states.has('locale')) heads.add('locale');

  const bindings = new Map(spec.bindings);
  const typeScope = new Map(spec.typeScope);
  const localNames = new Set(spec.locals.map((local) => local.name));
  const hookLines: string[] = [];

  for (const [name] of app.states) {
    if (bindings.has(name) || localNames.has(name) || !heads.has(name)) continue;
    const js = camelCase(name);
    const setter = 'set' + pascalCase(name);
    bindings.set(name, { kind: 'state', js, setter });
    uses.useStore = true;
    uses.stores.add(storeName(name));
    hookLines.push(`  const [${js}, ${setter}] = useStore(${storeName(name)});`);
  }

  for (const [name, imp] of app.imports) {
    if (bindings.has(name) || localNames.has(name) || !heads.has(name)) continue;
    const local = camelCase(name);
    bindings.set(name, { kind: 'js', js: local });
    addJsImport(uses, imp.module, imp.jsName, local, imp.isDefault);
  }

  for (const name of app.functions.keys()) {
    if (bindings.has(name) || localNames.has(name) || !heads.has(name)) continue;
    bindings.set(name, { kind: 'fn', js: camelCase(name) });
  }

  for (const name of app.enums.keys()) {
    if (bindings.has(name) || localNames.has(name)) continue;
    bindings.set(name, { kind: 'enum', js: '' });
  }

  const resourceUrls = new Map([...app.resources].map(([name, r]) => [name, r.url]));
  const stateCtx: ExprCtx = { bindings, classFor, uses, sameFileComponents: sameFile, resourceUrls, defaultLocale: app.defaultLocale };

  for (const [name, resource] of app.resources) {
    if (bindings.has(name) || localNames.has(name) || !heads.has(name)) continue;
    const js = camelCase(name);
    bindings.set(name, { kind: 'resource', js });
    uses.useResource = true;
    const initial = resource.defaultValue !== undefined ? genExpr(resource.defaultValue, stateCtx) : undefined;
    const args: string[] = [JSON.stringify(resource.url)];
    if (initial !== undefined || resource.poll !== undefined || resource.live) args.push(initial ?? 'undefined');
    if (resource.poll !== undefined || resource.live) args.push(resource.poll !== undefined ? String(resource.poll) : 'undefined');
    if (resource.live) args.push('true');
    const resourceInfo = typeScope.get(name);
    const resourceType = resourceInfo === undefined ? 'any' : typeScriptType(bindingInfo(resourceInfo), app.tables);
    hookLines.push(`  const ${js} = useResource<${resourceType}>(${args.join(', ')});`);
  }

  for (const local of spec.locals) {
    const js = camelCase(local.name);
    const setter = 'set' + pascalCase(local.name);
    const initial = '__grhmInitial' + pascalCase(local.name);
    const reactSetter = '__grhmSet' + pascalCase(local.name);
    const type = inferTsType(local.init, typeScope, app);
    uses.useState = true;
    // React interprets function arguments as initializers/updaters. Evaluate
    // GRHM values eagerly once, then give React a pure closure returning the
    // captured value so function-valued locals remain ordinary values.
    hookLines.push(`  const ${initial} = ${genExpr(local.init, stateCtx)};`);
    hookLines.push(`  const [${js}, ${reactSetter}] = useState<${type}>(() => ${initial});`);
    hookLines.push(`  const ${setter} = (__grhmValue: ${type}): void => ${reactSetter}(() => __grhmValue);`);
    typeScope.set(local.name, initializerInfo('local', local.init, typeScope, app));
    bindings.set(local.name, { kind: 'local', js, setter });
  }

  const ctx: TsxCtx = { app, typeScope, bindings, classFor, uses, sameFileComponents: sameFile, synthHooks: [], resourceUrls, defaultLocale: app.defaultLocale };

  if (spec.title !== undefined) {
    uses.effect = true;
    const titleExpr = genExpr(spec.title, stateCtx);
    ctx.synthHooks.push('  useEffect(() => {');
    ctx.synthHooks.push(`    document.title = String(${titleExpr});`);
    ctx.synthHooks.push('  });');
  }

  let bodyJsx: string;
  if (spec.body.length === 1 && spec.body[0] !== undefined && isList(spec.body[0])) {
    const body = spec.body[0];
    // Compositions emit JSX child expressions, which need an enclosing
    // element even when they are the entire page or component body.
    if (['each', 'if', 'when', 'slot'].includes(opName(body) ?? '')) {
      bodyJsx = '<>\n      ' + genChild(body, ctx, 6) + '\n    </>';
    } else {
      bodyJsx = genChild(body, ctx, 4);
    }
  } else {
    const lines = spec.body.map((e) => '      ' + genChild(e, ctx, 6));
    bodyJsx = '<>\n' + lines.join('\n') + '\n    </>';
  }

  const lines: string[] = [];
  lines.push(`export function ${spec.fnName}(${spec.propsParam}): ReactElement {`);
  lines.push(...hookLines);
  lines.push(...ctx.synthHooks);
  lines.push('  return (');
  lines.push('    ' + bodyJsx);
  lines.push('  );');
  lines.push('}');
  return lines.join('\n');
}

export function pageFnName(page: PageModel): string {
  return 'Page' + pascalCase(page.name);
}

function genPageFn(page: PageModel, app: AppModel, classFor: Map<string, string>, uses: FileUses): string {
  const heads = collectHeads([...page.body, ...page.locals.map((l) => l.init), ...(page.title !== undefined ? [page.title] : [])]);
  const usesParams = page.params.some((p) => heads.has(p));
  const bindings = new Map<string, Binding>();
  for (const param of page.params) {
    bindings.set(param, { kind: 'param', js: `__grhmProps.params[${JSON.stringify(param)}] ?? ''` });
  }
  return emitFunction(
    {
      fnName: pageFnName(page),
      propsParam: `${usesParams ? '__grhmProps' : '_props'}: { params: Record<string, string> }`,
      body: page.body,
      locals: page.locals,
      bindings,
      typeScope: pageInitializerScope(app, page),
      title: page.title,
    },
    app,
    classFor,
    uses,
    new Set(),
  );
}

function genComponentFn(component: ComponentModel, app: AppModel, classFor: Map<string, string>, uses: FileUses, sameFile: Set<string>): { iface: string; fn: string; needsReactNode: boolean } {
  const name = pascalCase(component.name);
  const ifaceName = `${name}Props`;
  const propLines = component.props.map((p) => `  ${camelCase(p.name)}: ${propTsType(p.type)};`);
  if (component.hasSlot) propLines.push('  children?: ReactNode;');
  const iface = `export interface ${ifaceName} {\n${propLines.join('\n')}\n}`;

  const bindings = new Map<string, Binding>();
  for (const prop of component.props) {
    bindings.set(prop.name, {
      kind: prop.type === 'action' ? 'action' : 'prop',
      js: `__grhmProps.${camelCase(prop.name)}`,
    });
  }

  const usesProps = component.props.length > 0 || component.hasSlot;
  const fn = emitFunction(
    {
      fnName: name,
      propsParam: `${usesProps ? '__grhmProps' : '_props'}: ${ifaceName}`,
      body: component.body,
      locals: component.locals,
      bindings,
      typeScope: componentInitializerScope(app, component),
    },
    app,
    classFor,
    uses,
    sameFile,
  );
  return { iface, fn, needsReactNode: component.hasSlot };
}

function reactImports(uses: FileUses, needs: { reactElement: boolean; reactNode: boolean }): string {
  const value: string[] = [];
  if (uses.fragment) value.push('Fragment as __grhmFragment');
  if (uses.effect) value.push('useEffect');
  if (uses.useState) value.push('useState');
  if (uses.useId) value.push('useId as __grhmUseId');
  const types: string[] = [];
  if (uses.changeEvent) types.push('ChangeEvent');
  if (uses.formEvent) types.push('FormEvent');
  if (uses.mouseEvent) types.push('MouseEvent');
  if (needs.reactElement) types.push('ReactElement');
  if (needs.reactNode) types.push('ReactNode');
  let out = '';
  if (value.length > 0) out += `import { ${value.join(', ')} } from 'react';\n`;
  if (types.length > 0) out += `import type { ${types.join(', ')} } from 'react';\n`;
  return out;
}

function runtimeImports(uses: FileUses, prefix: string): string {
  const names: string[] = [];
  if (uses.useStore) names.push('useStore');
  if (uses.useResource) names.push('useResource');
  if (uses.navigate) names.push('navigate');
  if (uses.fmtMoney) names.push('fmtMoney');
  if (uses.send) names.push('send');
  if (uses.refresh) names.push('refreshResource');
  if (uses.toast) names.push('showToast');
  if (uses.dialog) names.push('DialogShell');
  if (uses.upload) names.push('uploadFile');
  if (uses.menu) names.push('useMenu as __grhmUseMenu');
  if (uses.tabs) names.push('tabKeyDown as __grhmTabKeyDown');
  names.push(...[...uses.helpers].sort());
  let out = '';
  if (names.length > 0) out += `import { ${names.join(', ')} } from '${prefix}runtime';\n`;
  if (uses.i18n) out += `import { tMsg } from '${prefix}i18n';\n`;
  return out;
}

function genComponentsFile(app: AppModel, classFor: Map<string, string>, outDirDepth: number): string | undefined {
  if (app.components.size === 0) return undefined;
  const uses = newUses();
  const sameFile = new Set([...app.components.values()].map((c) => pascalCase(c.name)));
  const chunks: string[] = [];
  let needsReactNode = false;
  for (const [, component] of app.components) {
    const { iface, fn, needsReactNode: nrn } = genComponentFn(component, app, classFor, uses, sameFile);
    needsReactNode = needsReactNode || nrn;
    chunks.push(iface + '\n\n' + fn);
  }
  let out = HEADER;
  out += reactImports(uses, { reactElement: true, reactNode: needsReactNode });
  out += runtimeImports(uses, './');
  if (uses.stores.size > 0) out += `import { ${[...uses.stores].join(', ')} } from './state';\n`;
  out += libImportLines(uses, './');
  out += jsImportLines(uses, 0, outDirDepth);
  return out + '\n' + chunks.join('\n\n') + '\n';
}

/** File name (under gen/pages/) for one page module. */
export function pageFileName(page: PageModel): string {
  return page.name.toLowerCase().replace(/[^a-z0-9-]+/g, '-');
}

function genPageFile(page: PageModel, app: AppModel, classFor: Map<string, string>, outDirDepth: number): string {
  const uses = newUses();
  const fn = genPageFn(page, app, classFor, uses);
  let out = HEADER;
  out += reactImports(uses, { reactElement: true, reactNode: false });
  out += runtimeImports(uses, '../');
  if (uses.stores.size > 0) out += `import { ${[...uses.stores].join(', ')} } from '../state';\n`;
  if (uses.components.size > 0) out += `import { ${[...uses.components].sort().join(', ')} } from '../components';\n`;
  out += libImportLines(uses, '../');
  out += jsImportLines(uses, 1, outDirDepth);
  return out + '\n' + fn + '\n';
}

function genAppFile(app: AppModel): string {
  let out = HEADER;
  out += "import { Suspense, lazy, useEffect } from 'react';\n";
  out += "import type { ReactElement } from 'react';\n";
  out += "import { ErrorBoundary, Toasts, matchRoute, usePath } from './runtime';\n";
  out += '\n';
  // Per-page code splitting: each page is its own chunk, loaded on demand.
  for (const page of app.pages) {
    out += `const ${pageFnName(page)} = lazy(() => import('./pages/${pageFileName(page)}').then((m) => ({ default: m.${pageFnName(page)} })));\n`;
  }
  out += '\n';
  out += 'interface RouteDef {\n  pattern: string;\n  ownsTitle: boolean;\n  render: (params: Record<string, string>) => ReactElement;\n}\n\n';
  out += 'const routes: RouteDef[] = [\n';
  const orderedPages = [...app.pages].sort((a, b) => {
    const specificity = (route: string): number => route.split('/').filter(Boolean).filter((segment) => !/^\{[^}]+\}$/.test(segment)).length;
    return specificity(b.route) - specificity(a.route);
  });
  for (const page of orderedPages) {
    out += `  { pattern: ${JSON.stringify(page.route)}, ownsTitle: ${page.title !== undefined}, render: (params) => <${pageFnName(page)} params={params} /> },\n`;
  }
  out += '];\n\n';
  out += `const APP_TITLE = ${JSON.stringify(app.name)};\n\n`;
  out += 'export function App(): ReactElement {\n';
  out += '  const path = usePath();\n';
  out += '  let page: ReactElement | undefined;\n';
  out += '  let ownsTitle = false;\n';
  out += '  for (const route of routes) {\n';
  out += '    const params = matchRoute(route.pattern, path);\n';
  out += '    if (params !== null) {\n';
  out += '      page = route.render(params);\n';
  out += '      ownsTitle = route.ownsTitle;\n';
  out += '      break;\n';
  out += '    }\n';
  out += '  }\n';
  out += '  useEffect(() => {\n';
  out += '    if (!ownsTitle) document.title = APP_TITLE;\n';
  out += '  }, [path, ownsTitle]);\n';
  out += '  return (\n';
  out += '    <ErrorBoundary key={path}>\n';
  out += '      <Suspense fallback={<div className="g-loading" aria-busy="true" />}>\n';
  out += '        {page ?? <div className="g-notfound">No route matches {path}</div>}\n';
  out += '      </Suspense>\n';
  out += '      <Toasts />\n';
  out += '    </ErrorBoundary>\n';
  out += '  );\n';
  out += '}\n';
  return out;
}

