export interface Store<T> {
  get(): T;
  set(value: T): void;
  subscribe(listener: () => void): () => void;
}

export function createStore<T>(initial: T): Store<T> {
  let value = initial;
  const listeners = new Set<() => void>();
  return {
    get: () => value,
    set: (next: T) => {
      value = next;
      for (const listener of listeners) listener();
    },
    subscribe: (listener: () => void) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
  };
}

export function useStore<T>(store: Store<T>): [T, (value: T) => void] {
  const value = useSyncExternalStore(store.subscribe, store.get, store.get);
  return [value, store.set];
}

export interface Resource<T> {
  data: T | undefined;
  loading: boolean;
  error: string | undefined;
  reload(): void;
}

interface ResourceEntry<T> {
  store: Store<{ data: T | undefined; loading: boolean; error: string | undefined }>;
  started: boolean;
  /** Fetch generation: even a transport ignoring abort cannot publish stale data. */
  seq: number;
  invalidated?: boolean;
  controller?: AbortController;
  consumers: Map<object, number | undefined>;
  pollMs?: number;
  pollTimer?: ReturnType<typeof setInterval>;
  evictionTimer?: ReturnType<typeof setTimeout>;
}

/** Unused data survives brief remounts, but cannot accumulate indefinitely. */
const RESOURCE_RETENTION_MS = 30_000;
const MAX_UNUSED_RESOURCES = 128;
const resourceCache = new Map<string, ResourceEntry<unknown>>();
const unusedResources = new Map<string, ResourceEntry<unknown>>();

function stopPolling<T>(entry: ResourceEntry<T>): void {
  if (entry.pollTimer !== undefined) clearInterval(entry.pollTimer);
  entry.pollTimer = undefined;
  entry.pollMs = undefined;
}

function cancelFetch<T>(entry: ResourceEntry<T>): void {
  entry.invalidated = false;
  if (entry.controller === undefined) return;
  const controller = entry.controller;
  entry.controller = undefined;
  entry.seq++;
  entry.started = false;
  controller.abort();
  const current = entry.store.get();
  entry.store.set({ ...current, loading: false });
}

function forgetUnused<T>(url: string, entry: ResourceEntry<T>): void {
  if (entry.evictionTimer !== undefined) clearTimeout(entry.evictionTimer);
  entry.evictionTimer = undefined;
  if (unusedResources.get(url) === entry) unusedResources.delete(url);
}

function evictResource<T>(url: string, entry: ResourceEntry<T>): void {
  if (entry.consumers.size !== 0) return;
  forgetUnused(url, entry);
  stopPolling(entry);
  cancelFetch(entry);
  entry.started = false;
  if (resourceCache.get(url) === entry) resourceCache.delete(url);
}

function retainUnused<T>(url: string, entry: ResourceEntry<T>): void {
  if (resourceCache.get(url) !== entry || entry.consumers.size !== 0) return;
  forgetUnused(url, entry);
  unusedResources.set(url, entry as ResourceEntry<unknown>);
  entry.evictionTimer = setTimeout(() => evictResource(url, entry), RESOURCE_RETENTION_MS);
  while (unusedResources.size > MAX_UNUSED_RESOURCES) {
    const oldest = unusedResources.entries().next().value;
    if (oldest === undefined) break;
    evictResource(oldest[0], oldest[1]);
  }
}

function resourceEntry<T>(url: string, initial?: T): ResourceEntry<T> {
  let entry = resourceCache.get(url) as ResourceEntry<T> | undefined;
  if (entry === undefined) {
    entry = { store: createStore({ data: initial, loading: true, error: undefined }), started: false, seq: 0, consumers: new Map() };
    resourceCache.set(url, entry as ResourceEntry<unknown>);
    // Rendered trees that never commit are bounded by the same retention policy.
    retainUnused(url, entry);
  }
  return entry;
}

async function startFetch<T>(url: string, entry: ResourceEntry<T>): Promise<void> {
  if (resourceCache.get(url) !== entry || entry.consumers.size === 0) return;
  const seq = ++entry.seq;
  entry.controller?.abort();
  const controller = new AbortController();
  entry.controller = controller;
  entry.started = true;
  const current = entry.store.get();
  entry.store.set({ data: current.data, loading: true, error: undefined });
  let denied = false;
  try {
    const response = await fetch(apiUrl(url), { signal: controller.signal, credentials: 'include' });
    if (seq !== entry.seq || controller.signal.aborted) return;
    if (!response.ok) {
      denied = response.status === 401 || response.status === 403;
      throw new Error('HTTP ' + response.status);
    }
    const data = await response.json() as T;
    if (seq !== entry.seq || controller.signal.aborted) return;
    entry.store.set({ data, loading: false, error: undefined });
  } catch (err: unknown) {
    if (seq !== entry.seq || controller.signal.aborted) return;
    reportRuntimeError(err, 'resource');
    const message = err instanceof Error ? err.message : String(err);
    const stale = entry.store.get();
    entry.store.set({ data: denied ? undefined : stale.data, loading: false, error: message });
  } finally {
    if (seq === entry.seq) {
      entry.controller = undefined;
      const invalidated = entry.invalidated;
      entry.invalidated = false;
      if (invalidated) void startFetch(url, entry);
    }
  }
}

function pollInterval(seconds: number | undefined): number | undefined {
  if (seconds === undefined || !Number.isFinite(seconds) || seconds <= 0) return undefined;
  // Browser timers accept signed 32-bit millisecond delays.
  return Math.min(2_147_483_647, Math.max(1, seconds * 1000));
}

function updatePolling<T>(url: string, entry: ResourceEntry<T>): void {
  let fastest: number | undefined;
  for (const interval of entry.consumers.values()) {
    if (interval !== undefined && (fastest === undefined || interval < fastest)) fastest = interval;
  }
  if (fastest === entry.pollMs) return;
  stopPolling(entry);
  if (fastest === undefined) return;
  entry.pollMs = fastest;
  entry.pollTimer = setInterval(() => {
    // Slow requests finish normally; a timer never duplicates or aborts them.
    if (entry.controller === undefined) void startFetch(url, entry);
  }, fastest);
}

/** Re-fetch active consumers; invalidate retained data for the next mount. */
export function refreshResource(url: string): void {
  const entry = resourceCache.get(url);
  if (entry === undefined) return;
  if (entry.consumers.size > 0) void startFetch(url, entry);
  else entry.started = false;
}

/** Cancel every request/timer and discard cached data; used by tests. */
export function resetResources(): void {
  const entries = [...resourceCache.values()];
  resourceCache.clear();
  unusedResources.clear();
  liveUrls.clear();
  closeLiveSource();
  for (const entry of entries) {
    entry.consumers.clear();
    stopPolling(entry);
    if (entry.evictionTimer !== undefined) clearTimeout(entry.evictionTimer);
    entry.evictionTimer = undefined;
    cancelFetch(entry);
    // Mounted subscribers re-read the cache after reset, including entries
    // that had already completed and therefore had no request to cancel.
    entry.store.set({ data: undefined, loading: true, error: undefined });
  }
}

// Cookies are shared between tabs, so authentication changes must invalidate
// retained data in every tab as well as cancel in-flight requests locally.
let sessionChannel: BroadcastChannel | undefined;
function connectSessionChannel(): void {
  if (sessionChannel !== undefined || typeof window === 'undefined' || typeof BroadcastChannel === 'undefined') return;
  sessionChannel = new BroadcastChannel('grhm-session');
  sessionChannel.onmessage = (event: MessageEvent) => {
    if (event.data === 'changed') resetResources();
  };
}

function sessionChanged(): void {
  resetResources();
  connectSessionChannel();
  sessionChannel?.postMessage('changed');
}

// Live resources: one shared EventSource to the generated server's change
// feed. Every :live resource re-fetches when any db mutation is broadcast.
const liveUrls = new Map<string, Set<object>>();
let liveSource: EventSource | undefined;
const liveRoutes: { pattern: string; id: string }[] = /* GRHM_LIVE_ROUTES */ [];

// Complete useful in-flight work and issue at most one trailing revalidation.
// Repeated events must never keep aborting a slow resource indefinitely.
function refreshLiveResource(url: string): void {
  const entry = resourceCache.get(url);
  if (entry === undefined) return;
  if (entry.controller !== undefined) entry.invalidated = true;
  else refreshResource(url);
}

function closeLiveSource(): void {
  if (liveSource === undefined) return;
  liveSource.onmessage = null;
  liveSource.onopen = null;
  liveSource.close();
  liveSource = undefined;
}

function subscribeLive(url: string): () => void {
  const subscribers = liveUrls.get(url) ?? new Set<object>();
  const subscriber = {};
  subscribers.add(subscriber);
  liveUrls.set(url, subscribers);
  if (liveSource === undefined && typeof EventSource !== 'undefined') {
    const source = new EventSource(apiUrl('/api/_events'), { withCredentials: true });
    liveSource = source;
    source.onopen = () => {
      if (source !== liveSource) return;
      for (const liveUrl of liveUrls.keys()) refreshLiveResource(liveUrl);
    };
    source.onmessage = (event) => {
      if (source !== liveSource) return;
      let affected: string[] | undefined;
      try { const data = JSON.parse(event.data) as { routes?: unknown }; if (Array.isArray(data.routes) && data.routes.every((id: unknown) => typeof id === 'string')) affected = data.routes; } catch { /* Revalidate for older servers or malformed events. */ }
      for (const liveUrl of liveUrls.keys()) {
        const route = liveRoutes.find((entry) => matchRoute(entry.pattern, liveUrl.split('?')[0] ?? liveUrl) !== null);
        if (affected === undefined || route === undefined || affected.includes(route.id)) refreshLiveResource(liveUrl);
      }
    };
  }
  return () => {
    subscribers.delete(subscriber);
    // A cleanup from before resetResources must not remove a new subscription.
    if (subscribers.size > 0 || liveUrls.get(url) !== subscribers) return;
    liveUrls.delete(url);
    if (liveUrls.size === 0) closeLiveSource();
  };
}

/**
 * JSON mutation against the app's own API; used by the (send ...) action.
 * The x-grhm header is the CSRF token check: the server rejects mutations
 * without it, and cross-site forms cannot set custom headers.
 */
export async function send(method: string, url: string, body?: unknown): Promise<unknown> {
  const headers: Record<string, string> = { 'x-grhm': '1' };
  if (body !== undefined) headers['Content-Type'] = 'application/json';
  const response = await fetch(apiUrl(url), {
    credentials: 'include',
    method: method.toUpperCase(),
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  if (!response.ok) {
    let message = method.toUpperCase() + ' ' + url + ': HTTP ' + response.status;
    try {
      const payload: unknown = await response.json();
      if (typeof payload === 'object' && payload !== null && typeof (payload as { error?: unknown }).error === 'string') {
        message = (payload as { error: string }).error;
      }
    } catch {
      // Non-JSON error body; keep the status message.
    }
    reportRuntimeError(message, 'request', response.headers?.get('x-request-id') ?? undefined);
    throw new Error(message);
  }
  const pathname = url.split(/[?#]/)[0];
  if (method.toUpperCase() === 'POST' && ['/api/auth/signup', '/api/auth/login', '/api/auth/logout', '/api/auth/logout-all'].includes(pathname ?? '')) sessionChanged();
  const text = await response.text();
  return text === '' ? undefined : JSON.parse(text);
}

export function useResource<T>(url: string, initial?: T, pollSeconds?: number, live?: boolean): Resource<T> {
  const entry = resourceEntry<T>(url, initial);
  const consumer = useRef<object>({}).current;
  const state = useSyncExternalStore(entry.store.subscribe, entry.store.get, entry.store.get);
  // Lifetime and polling configuration are separate so interval changes do
  // not briefly remove the final consumer and abort a healthy request.
  useEffect(() => {
    connectSessionChannel();
    const cached = resourceCache.get(url);
    if (cached !== undefined && cached !== entry) {
      // A concurrent render can commit after its inactive entry was evicted.
      // Notify the hook so it subscribes to the current entry on its next render.
      entry.store.set({ ...entry.store.get() });
      return;
    }
    resourceCache.set(url, entry as ResourceEntry<unknown>);
    forgetUnused(url, entry);
    entry.consumers.set(consumer, pollInterval(pollSeconds));
    updatePolling(url, entry);
    if (!entry.started) void startFetch(url, entry);
    return () => {
      entry.consumers.delete(consumer);
      if (resourceCache.get(url) !== entry) return;
      updatePolling(url, entry);
      if (entry.consumers.size === 0) {
        cancelFetch(entry);
        retainUnused(url, entry);
      }
    };
  }, [url, entry, consumer]);
  useEffect(() => {
    if (!entry.consumers.has(consumer)) return;
    entry.consumers.set(consumer, pollInterval(pollSeconds));
    updatePolling(url, entry);
  }, [url, entry, consumer, pollSeconds]);
  useEffect(() => {
    if (live === true && resourceCache.get(url) === entry) return subscribeLive(url);
  }, [url, entry, live]);
  return {
    data: state.data,
    loading: state.loading,
    error: state.error,
    reload: () => refreshResource(url),
  };
}

/** Upload one file to the generated server; resolves to its public /uploads URL. */
export async function uploadFile(file: File): Promise<string> {
  const response = await fetch(apiUrl('/api/uploads'), {
    credentials: 'include',
    method: 'POST',
    headers: { 'x-grhm': '1', 'x-filename': encodeURIComponent(file.name), 'Content-Type': 'application/octet-stream' },
    body: file,
  });
  if (!response.ok) {
    let message = 'upload failed: HTTP ' + response.status;
    try {
      const payload: unknown = await response.json();
      if (typeof payload === 'object' && payload !== null && typeof (payload as { error?: unknown }).error === 'string') {
        message = (payload as { error: string }).error;
      }
    } catch {
      // Non-JSON error body; keep the status message.
    }
    reportRuntimeError(message, 'request', response.headers?.get('x-request-id') ?? undefined);
    throw new Error(message);
  }
  const payload = (await response.json()) as { url: string };
  return apiUrl(payload.url);
}

