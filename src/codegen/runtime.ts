interface ErrorBoundaryProps {
  children?: ReactNode;
}

interface ErrorBoundaryState {
  error: Error | undefined;
}

/**
 * Catches runtime errors and reports them as structured diagnostics on the
 * console so agents can correlate failures with semantic nodes (via the
 * data-g attributes present in the rendered DOM).
 */
export class ErrorBoundary extends Component<ErrorBoundaryProps, ErrorBoundaryState> {
  state: ErrorBoundaryState = { error: undefined };

  static getDerivedStateFromError(error: Error): ErrorBoundaryState {
    return { error };
  }

  componentDidCatch(error: Error, info: { componentStack?: string | null }): void {
    reportRuntimeError(error, 'render');
    console.error(
      JSON.stringify({
        schema: 1,
        kind: 'runtime-error',
        message: error.message,
        stack: error.stack,
        componentStack: info.componentStack ?? undefined,
      }),
    );
  }

  render(): ReactNode {
    if (this.state.error !== undefined) {
      return createElement(
        'div',
        { className: 'g-runtime-error', role: 'alert' },
        createElement('p', null, 'This page could not load.'),
        createElement('button', { type: 'button', onClick: () => window.location.reload() }, 'Reload page'),
      );
    }
    return this.props.children;
  }
}
