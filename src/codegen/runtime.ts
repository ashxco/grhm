/** Match a "/route/{param}" pattern against a path; shared by client routing and the server. */
export function matchRoute(pattern: string, path: string): Record<string, string> | null {
  const patternSegs = pattern.split('/').filter((s) => s !== '');
  const pathSegs = path.split('/').filter((s) => s !== '');
  if (patternSegs.length !== pathSegs.length) return null;
  const params: Record<string, string> = {};
  for (let i = 0; i < patternSegs.length; i += 1) {
    const p = patternSegs[i];
    const a = pathSegs[i];
    if (p === undefined || a === undefined) return null;
    if (p.startsWith('{') && p.endsWith('}')) {
      params[p.slice(1, -1)] = safeDecode(a);
    } else if (p !== a) {
      return null;
    }
  }
  return params;
}
