const inertOwners = new Map<HTMLElement, { count: number; previous: boolean }>();

/** Traps focus in the topmost dialog and makes background content inert. */
export function DialogShell(props: { onClose: () => void; children?: ReactNode }): ReactElement {
  const ref = useRef<HTMLDivElement>(null);
  const closeRef = useRef(props.onClose);
  closeRef.current = props.onClose;
  useEffect(() => {
    const root = ref.current;
    if (root === null) return;
    const active = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    // Child effects can run before parent effects when both dialogs mount.
    // Keep descendants above ancestors regardless of effect order, and carry
    // the original opener through a simultaneously mounted child.
    const descendantIndex = activeDialogs.findIndex((dialog) => root.contains(dialog));
    const descendant = activeDialogs[descendantIndex];
    const previous = active !== null && root.contains(active) && descendant !== undefined
      ? dialogPrevious.get(descendant) ?? null : active;
    dialogPrevious.set(root, previous);
    if (descendantIndex >= 0) activeDialogs.splice(descendantIndex, 0, root);
    else activeDialogs.push(root);
    const background: HTMLElement[] = [];
    let branch: HTMLElement = root;
    while (branch.parentElement && branch !== document.body) {
      for (const sibling of Array.from(branch.parentElement.children)) {
        if (!(sibling instanceof HTMLElement) || sibling === branch) continue;
        const owner = inertOwners.get(sibling) ?? { count: 0, previous: sibling.inert };
        owner.count++;
        inertOwners.set(sibling, owner);
        sibling.inert = true;
        background.push(sibling);
      }
      branch = branch.parentElement;
    }
    const isTop = () => root.isConnected && activeDialogs[activeDialogs.length - 1] === root;
    const focusFirst = () => (focusable(root)[0] ?? root).focus();
    focusFirst();
    const onFocus = (event: FocusEvent) => {
      if (isTop() && event.target instanceof Node && !root.contains(event.target)) focusFirst();
    };
    const onKey = (event: KeyboardEvent) => {
      if (!isTop()) return;
      if (event.key === 'Escape') { event.preventDefault(); event.stopPropagation(); closeRef.current(); return; }
      if (event.key !== 'Tab') return;
      const items = focusable(root);
      const first = items[0];
      const last = items[items.length - 1];
      if (items.length === 0) { event.preventDefault(); root.focus(); }
      else if (event.shiftKey && (document.activeElement === first || document.activeElement === root)) {
        event.preventDefault(); last?.focus();
      } else if (!event.shiftKey && (document.activeElement === last || document.activeElement === root)) {
        event.preventDefault(); first?.focus();
      }
    };
    root.addEventListener('keydown', onKey);
    document.addEventListener('focusin', onFocus);
    return () => {
      root.removeEventListener('keydown', onKey);
      document.removeEventListener('focusin', onFocus);
      const index = activeDialogs.indexOf(root);
      if (index >= 0) activeDialogs.splice(index, 1);
      for (const sibling of background) {
        const owner = inertOwners.get(sibling);
        if (owner && --owner.count === 0) { sibling.inert = owner.previous; inertOwners.delete(sibling); }
      }
      if (previous?.isConnected) previous.focus();
      const remaining = activeDialogs[activeDialogs.length - 1];
      if (remaining?.isConnected && !remaining.contains(document.activeElement)) {
        (focusable(remaining)[0] ?? remaining).focus();
      }
    };
  }, []);
  return createElement('div', { ref, tabIndex: -1, className: 'g-dialog-shell' }, props.children);
}

