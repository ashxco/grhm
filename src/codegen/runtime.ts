const FOCUSABLE = 'button, [href], input, select, textarea, [tabindex]';
function focusable(root: HTMLElement): HTMLElement[] {
  return Array.from(root.querySelectorAll<HTMLElement>(FOCUSABLE)).filter((item) =>
    item.tabIndex >= 0 && !item.matches(':disabled, [inert], [inert] *') &&
    item.getClientRects().length > 0 && getComputedStyle(item).visibility !== 'hidden');
}

export function tabKeyDown(event: ReactKeyboardEvent<HTMLElement>, select: (index: number) => void): void {
  const items = Array.from(event.currentTarget.querySelectorAll<HTMLElement>('[role="tab"]'));
  const current = items.indexOf(document.activeElement as HTMLElement);
  if (current < 0 || items.length === 0) return;
  const direction = getComputedStyle(event.currentTarget).direction === 'rtl' ? -1 : 1;
  let next: number;
  switch (event.key) {
    case 'ArrowRight': next = (current + direction + items.length) % items.length; break;
    case 'ArrowLeft': next = (current - direction + items.length) % items.length; break;
    case 'Home': next = 0; break;
    case 'End': next = items.length - 1; break;
    default: return;
  }
  event.preventDefault();
  select(next);
  items[next]?.focus();
}

export function useMenu() {
  const [open, setOpen] = useState(false);
  const id = useId();
  const root = useRef<HTMLDivElement>(null);
  const trigger = useRef<HTMLButtonElement>(null);
  const last = useRef(false);
  const items = () => Array.from(root.current?.querySelectorAll<HTMLElement>('[role="menuitem"]') ?? []);
  const close = (restore = true) => { setOpen(false); if (restore) trigger.current?.focus(); };
  useEffect(() => {
    if (!open) return;
    const choices = items();
    (choices[last.current ? choices.length - 1 : 0] ?? root.current?.querySelector<HTMLElement>('[role="menu"]'))?.focus();
    const outside = (event: PointerEvent) => {
      if (event.target instanceof Node && !root.current?.contains(event.target)) close(false);
    };
    document.addEventListener('pointerdown', outside);
    return () => document.removeEventListener('pointerdown', outside);
  }, [open]);
  return {
    open, close,
    rootProps: { ref: root, onBlur: (event: ReactFocusEvent<HTMLDivElement>) => {
      if (!event.currentTarget.contains(event.relatedTarget)) close(false);
    } },
    triggerProps: {
      ref: trigger, id: id + '-trigger', 'aria-haspopup': 'menu' as const,
      'aria-expanded': open, 'aria-controls': open ? id : undefined,
      onClick: () => { last.current = false; setOpen(!open); },
      onKeyDown: (event: ReactKeyboardEvent<HTMLButtonElement>) => {
        if (event.key !== 'ArrowDown' && event.key !== 'ArrowUp') return;
        event.preventDefault();
        last.current = event.key === 'ArrowUp';
        if (open) { const choices = items(); choices[last.current ? choices.length - 1 : 0]?.focus(); }
        else setOpen(true);
      },
    },
    menuProps: {
      id, role: 'menu' as const, tabIndex: -1, 'aria-labelledby': id + '-trigger',
      onKeyDown: (event: ReactKeyboardEvent<HTMLDivElement>) => {
        const choices = items();
        const current = choices.indexOf(document.activeElement as HTMLElement);
        let next: number | undefined;
        switch (event.key) {
          case 'Escape': event.preventDefault(); event.stopPropagation(); close(); return;
          case 'Tab': close(); return;
          case 'ArrowDown': next = (current + 1) % choices.length; break;
          case 'ArrowUp': next = (current - 1 + choices.length) % choices.length; break;
          case 'Home': next = 0; break;
          case 'End': next = choices.length - 1; break;
          default:
            if (event.key.length === 1 && !event.ctrlKey && !event.metaKey && !event.altKey) {
              for (let offset = 1; offset <= choices.length; offset++) {
                const index = (current + offset) % choices.length;
                if (choices[index]?.textContent?.trim().toLowerCase().startsWith(event.key.toLowerCase())) { next = index; break; }
              }
            }
        }
        if (next !== undefined) { event.preventDefault(); choices[next]?.focus(); }
      },
    },
  };
}

