import fs from 'node:fs';

const cache = new Map<string, string>();
/** The build copies these audited TypeScript sources beside compiled output. */
export function runtimeSource(name: 'storage' | 'http-files' | 'static-server' | 'uploads' | 'db-admin' | 'controls' | 'contracts'): string {
  let source = cache.get(name);
  if (source === undefined) {
    source = '/* Generated by grhm. Standalone runtime module. */\n' + fs.readFileSync(new URL('../runtime/' + name + '.ts', import.meta.url), 'utf8');
    source = source.replace(/from '(\.\/[^']+)\.js'/g, "from '$1.ts'");
    cache.set(name, source);
  }
  return source;
}
